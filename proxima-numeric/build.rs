//! Build-time sizing for proxima-numeric per principle 12: reads `proxima-numeric.toml`, applies
//! `PROXIMA_NUMERIC_<SECTION>_<KEY>` overrides and emits `OUT_DIR/proxima_numeric_sized.rs`,
//! which `src/sized.rs` includes.

use std::env;
use std::fs;
use std::path::PathBuf;

use proxima_build::sizing::{SizingSource, require_nonzero};

fn main() {
    // printing any rerun-if-changed disables cargo's implicit whole-package watch
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir =
        env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|err| panic!("CARGO_MANIFEST_DIR: {err}"));
    let source = SizingSource::load(&manifest_dir, "proxima-numeric.toml", "PROXIMA_NUMERIC")
        .unwrap_or_else(|err| panic!("{err}"));
    let window = source
        .resolve_int("convert", "window_elements")
        .unwrap_or_else(|err| panic!("{err}"));
    let window = require_nonzero("convert.window_elements", window);

    let out_dir =
        PathBuf::from(env::var_os("OUT_DIR").unwrap_or_else(|| panic!("OUT_DIR set by cargo")));
    let generated = format!(
        "// generated by build.rs from proxima-numeric.toml; override with PROXIMA_NUMERIC_<SECTION>_<KEY>.\n\
         \n\
         /// Wide values `PackedRows::convert` holds at once.\n\
         pub const CONVERT_WINDOW_ELEMENTS: usize = {window};\n",
    );
    fs::write(out_dir.join("proxima_numeric_sized.rs"), generated)
        .unwrap_or_else(|err| panic!("write sized: {err}"));
}
