//! Real-traffic shape sweep for BGE-small-en-v1.5, answering the gap named
//! against `docs/discipline.md`'s sealed `bge_eval` number (6.061 ms/sentence
//! Accelerate / 7.521 NEON at S=7-9, batch=1): that number is three
//! sentences of 7/8/9 tokens, and real embedding traffic is document chunks
//! of 128-512 tokens at varied lengths and batch sizes -- none of which the
//! sealed harness exercises. This file measures three things directly
//! rather than assuming any of them:
//!
//! (A) sequence-length sweep -- S in {8,32,64,128,256,512} (512 = BGE's own
//!     `max_position_embeddings`, `config.json`), NEON and Accelerate, plus
//!     `width_tile_plan` gate engagement (N of the 96 gemm-shaped `MatMul`
//!     folds `bge_route_census.rs`'s own doc names) and the decline-reason
//!     census at each S.
//! (B) cache behaviour -- 200-call stream of varied pinned lengths through
//!     `cpu::evaluate_named`'s own process-global `ARENA_CACHE` (capacity
//!     8, FIFO, `cpu.rs::ARENA_CACHE_CAPACITY`), measuring hit vs miss wall
//!     time directly from per-call timing classified by
//!     `cpu::arena_cache_totals()` deltas.
//! (C) batch sweep -- batch in {1,8,32} at S=128, pinning `batch_size` in
//!     `lower_graph_pinned` the same way `sequence_length` is already
//!     pinned.
//!
//! Token content is synthetic (this crate has no BGE-compatible tokenizer,
//! see `bge_eval.rs`'s own doc), generated by one deterministic formula
//! (`synthetic_tokens`) so every id stays a valid BGE-small vocab index
//! (`vocab_size` 30522) without claiming to be real English -- real-word
//! semantics are irrelevant to a shape/cache/batch measurement. Embeddings
//! are dumped to `BGE_TRAFFIC_OUT_DIR` (plain text, one file per S) for the
//! companion onnxruntime harness to diff against out-of-process.

